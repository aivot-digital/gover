import {mkdir, readdir, readFile, writeFile} from 'node:fs/promises';
import {dirname, resolve} from 'node:path';
import {fileURLToPath} from 'node:url';

const scriptDir = dirname(fileURLToPath(import.meta.url));
const appDir = resolve(scriptDir, '..');
const backendSrcDir = resolve(appDir, '../backend/src/main/java');
const outputFile = resolve(appDir, 'src/data/permissions/permission.ts');

const providerFiles = [];
const permissions = [];

for (const file of await collectJavaFiles(backendSrcDir)) {
    const source = await readFile(file, 'utf8');

    if (!/\bimplements\s+PermissionProvider\b/.test(source)) {
        continue;
    }

    providerFiles.push(file);
    permissions.push(...readPermissions(file, source));
}

if (providerFiles.length === 0) {
    throw new Error(`No PermissionProvider implementations found in ${backendSrcDir}`);
}

if (permissions.length === 0) {
    throw new Error('No permissions found.');
}

assertUnique(permissions, 'name');
assertUnique(permissions, 'value');

permissions.sort((a, b) => a.name < b.name ? -1 : a.name > b.name ? 1 : 0);

await mkdir(dirname(outputFile), {recursive: true});
await writeFile(
    outputFile,
    [
        '// Generated by npm run generate:permissions. Do not edit manually.',
        '',
        'export enum Permission {',
        ...permissions.map(({name, value}) => `    ${name} = "${value}",`),
        '}',
        '',
    ].join('\n'),
    'utf8',
);

console.log(`Generated ${permissions.length} permissions from ${providerFiles.length} providers.`);

async function collectJavaFiles(dir) {
    const files = [];

    for (const entry of await readdir(dir, {withFileTypes: true})) {
        const path = resolve(dir, entry.name);

        if (entry.isDirectory()) {
            files.push(...await collectJavaFiles(path));
        } else if (entry.isFile() && entry.name.endsWith('.java')) {
            files.push(path);
        }
    }

    return files;
}

function readPermissions(file, source) {
    const constants = new Map();
    const constantPattern = /public\s+static\s+final\s+String\s+([A-Z0-9_]+)\s*=\s*"([^"]+)";/g;

    for (const match of source.matchAll(constantPattern)) {
        constants.set(match[1], match[2]);
    }

    const result = [];

    for (const argument of readPermissionEntryFirstArguments(source)) {
        if (/^[A-Z][A-Z0-9_]*$/.test(argument)) {
            const value = constants.get(argument);

            if (value == null) {
                throw new Error(`${file}: Cannot resolve permission constant ${argument}`);
            }

            result.push({file, name: argument, value});
            continue;
        }

        const stringLiteral = argument.match(/^"([^"]+)"$/);

        if (stringLiteral != null) {
            result.push({file, name: enumNameFromValue(stringLiteral[1]), value: stringLiteral[1]});
            continue;
        }

        throw new Error(`${file}: Unsupported PermissionEntry.of permission argument: ${argument}`);
    }

    if (result.length === 0) {
        throw new Error(`${file}: PermissionProvider has no PermissionEntry.of(...) entries`);
    }

    return result;
}

function readPermissionEntryFirstArguments(source) {
    const result = [];
    let index = 0;

    while ((index = source.indexOf('PermissionEntry.of', index)) !== -1) {
        const open = source.indexOf('(', index);

        if (open === -1) {
            throw new Error('PermissionEntry.of call has no opening parenthesis');
        }

        result.push(readFirstArgument(source, open + 1).trim());
        index = open + 1;
    }

    return result;
}

function readFirstArgument(source, start) {
    let depth = 0;
    let quote = null;
    let escaped = false;

    for (let i = start; i < source.length; i++) {
        const char = source[i];

        if (quote != null) {
            if (escaped) {
                escaped = false;
            } else if (char === '\\') {
                escaped = true;
            } else if (char === quote) {
                quote = null;
            }
            continue;
        }

        if (char === '"' || char === "'") {
            quote = char;
            continue;
        }

        if (char === '(') {
            depth++;
            continue;
        }

        if (char === ')') {
            if (depth === 0) {
                throw new Error('PermissionEntry.of call ended before first argument separator');
            }

            depth--;
            continue;
        }

        if (char === ',' && depth === 0) {
            return source.slice(start, i);
        }
    }

    throw new Error('PermissionEntry.of call has no first argument separator');
}

function enumNameFromValue(value) {
    const name = value.toUpperCase().replace(/[^A-Z0-9]+/g, '_').replace(/^_+|_+$/g, '');

    if (!/^[A-Z][A-Z0-9_]*$/.test(name)) {
        throw new Error(`Cannot derive enum name from permission value: ${value}`);
    }

    return name;
}

function assertUnique(items, property) {
    const seen = new Map();

    for (const item of items) {
        const previous = seen.get(item[property]);

        if (previous != null) {
            throw new Error(`Duplicate permission ${property} ${item[property]} in ${previous.file} and ${item.file}`);
        }

        seen.set(item[property], item);
    }
}
